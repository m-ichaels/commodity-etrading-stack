#!/usr/bin/env python3
"""results/summary.md from results/*.json.   python scripts/summarize.py [results]"""
import glob
import json
import os
import sys

import numpy as np

R = sys.argv[1] if len(sys.argv) > 1 else "results"
ROOTS = ["CL", "NG"]
NAMES = {"CL": "WTI crude (CL)", "NG": "Henry Hub gas (NG)"}
UNIT = {"CL": "$/bbl", "NG": "$/MMBtu"}
out = []


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def P(s=""):
    out.append(s)


def table(cols, rows):
    P("| " + " | ".join(cols) + " |"); P("|" + "---|" * len(cols))
    for r in rows:
        P("| " + " | ".join(str(c) for c in r) + " |")
    P()



def paired(a, b, B=2000, seed=7):
    """mean of a - b with a bootstrap 95% CI over the paired seeds"""
    a = np.asarray(a, float); b = np.asarray(b, float); d = a - b; rng = np.random.default_rng(seed)
    if len(d) < 2:
        return float(d.mean()), float("nan"), float("nan")
    m = np.array([d[rng.integers(0, len(d), len(d))].mean() for _ in range(B)])
    return float(d.mean()), float(np.quantile(m, 0.025)), float(np.quantile(m, 0.975))


HEDGE_ORDER = ["FrontStack", "Strip", "FactorMin", "ImpactAware"]


def paired_tables(d, n, label):
    cells = d["cells"]
    rows = []
    for h in sorted(set(c["hedger"] for c in cells), key=lambda h: HEDGE_ORDER.index(h) if h in HEDGE_ORDER else 9):
        for g in sorted(set(c["gamma"] for c in cells)):
            base = next((c for c in cells if c["hedger"] == h and abs(c["gamma"] - g) < 1e-15 and c["quoter"] == "Symmetric"), None)
            if not base:
                continue
            for c in cells:
                if c["hedger"] == h and abs(c["gamma"] - g) < 1e-15 and c["quoter"] != "Symmetric":
                    m, lo, hi = paired(c["pnl_by_seed"], base["pnl_by_seed"])
                    rows.append([h, f"{g:.0e}", c["quoter"], f"{m / n / 1e3:+.1f}", f"[{lo / n / 1e3:+.1f}, {hi / n / 1e3:+.1f}]", f"{100 * m / base['pnl']:+.1f}%", f"{1e3 * (c['pnl_per_var'] - base['pnl_per_var']):+.2f}"])
    if rows:
        P(f"{label}: each quoter minus Symmetric on the same seeds (paired bootstrap 95% CI over seeds):\n")
        table(["hedger", "gamma", "quoter", "P&L/day difference $k", "95% CI", "relative", "P&L/var difference x1e-3"], rows)
    rows = []
    for q in sorted(set(c["quoter"] for c in cells)):
        for g in sorted(set(c["gamma"] for c in cells)):
            base = next((c for c in cells if c["quoter"] == q and abs(c["gamma"] - g) < 1e-15 and c["hedger"] == "FrontStack"), None)
            if not base:
                continue
            for c in cells:
                if c["quoter"] == q and abs(c["gamma"] - g) < 1e-15 and c["hedger"] != "FrontStack":
                    m, lo, hi = paired(c["pnl_by_seed"], base["pnl_by_seed"])
                    dh = (c["decomposition"]["hedge_exec"] + c["decomposition"]["hedge_impact"] - base["decomposition"]["hedge_exec"] - base["decomposition"]["hedge_impact"]) / n / 1e3
                    rows.append([q, f"{g:.0e}", c["hedger"], f"{m / n / 1e3:+.1f}", f"[{lo / n / 1e3:+.1f}, {hi / n / 1e3:+.1f}]", f"{dh:+.1f}", f"{c['pnl_5min_std'] / 1e3:.2f} vs {base['pnl_5min_std'] / 1e3:.2f}"])
    if rows:
        P(f"{label}: each hedger minus FrontStack on the same seeds:\n")
        table(["quoter", "gamma", "hedger", "P&L/day difference $k", "95% CI", "hedge cost difference $k/day", "5-min std $k (vs FrontStack)"], rows)


P("# Results summary\n")
P("Generated by scripts/summarize.py from results/*.json. Costs and P&L in US dollars; prices in $/bbl (WTI) and $/MMBtu (Henry Hub).\n")

# ---- data ---------------------------------------------------------------------------------------------------------
rows = []
for root in ROOTS:
    d = load(f"datacheck_{root.lower()}.json")
    if d:
        gh = d["gap_histogram_since_2024_09"]; rows.append([root, d["n_days"], d["first"], d["last"], d["eia_days"], gh.get("0", 0), gh.get("1-3", 0), gh.get("4-12", 0), gh.get(">12", 0), d["first_complete_day"]])
if rows:
    P("## Data\n")
    P("Curve days by source: EIA front contracts 1-4 (1983/1993 to April 2024), then the listed contracts from Yahoo (daily, two years) merged with the continuous front; the histogram counts the missing delivery months within the first 24 for the days since September 2024.\n")
    table(["root", "curve days", "first", "last", "EIA-only days", "complete", "1-3 missing", "4-12 missing", ">12 missing", "first complete day"], rows)
    dp = load("data_parity.json")
    if dp:
        P("Source parity on the overlap days (EIA front contract vs the Yahoo continuous front): " + "; ".join(f"{k}: {v['yahoo_front']['n']} days, median |diff| {v['yahoo_front']['median_abs_diff']:.3f}, {100 * v['yahoo_front']['share_within_1pct_of_price']:.0f}% within 1% of the price" for k, v in dp.items()) + ".\n")

# ---- one-day curve --------------------------------------------------------------------------------------------------
for root in ROOTS:
    fs = sorted(glob.glob(os.path.join(R, f"curve_{root.lower()}_*.json")))
    if not fs:
        continue
    c = json.load(open(fs[-1], encoding="utf-8"))
    P(f"## {NAMES[root]}: curve construction on {c['date']} ({c['n_points']} contracts, {c['gap_months']} missing months in the first 24)\n")
    rows = []
    for m, lab in (("seasonal_nss", "seasonal NSS"), ("pspline", "P-spline"), ("kernel_ridge", "seasonal kernel ridge")):
        j = c["methods"][m]; rows.append([lab, f"{j['lambda']:.0e}" if j["lambda"] else "-", f"{j['in_sample_rmse']:.4f}", f"{j['loo_mean_abs']:.4f}", f"{j['loo_mean_abs_interior']:.4f}", f"{j['loo_mean_abs_pct']:.3f}%", " / ".join(f"{e:+.3f}" for e in j["extrapolation_err_last3"]), f"{j['strip_3m']:.4f}", f"{j['strip_12m']:.4f}", f"{sum(j['sens_month3_to_contracts']):.3f}"])
    table(["model", "lambda", "in-sample rmse", "LOO mean abs err", "interior", "LOO %", "extrapolation err (last 3)", "3m strip", "12m strip", "sum of month-3 key rates"], rows)
    j = c["methods"]["pspline" if root == "CL" else "kernel_ridge"]
    P("Calendar-month swaps off the selected model (business-day-weighted average of the contracts prompt on each day; legs marked * are priced off the model because the contract is not observed):\n")
    table(["month", "price", "business days", "legs (delivery x weight)"], [[s["month"], f"{s['price']:.4f}", s["business_days"], ", ".join(f"{l['delivery']} x {l['weight']:.3f}{'' if l['observed'] else '*'}" for l in s["legs"])] for s in j["calendar_swaps"]])

# ---- daily builds -----------------------------------------------------------------------------------------------------
for root in ROOTS:
    d = load(f"curvehist_{root.lower()}.json")
    if not d:
        continue
    P(f"## {NAMES[root]}: daily builds {d['from']}..{d['to']} ({d['n_days']} days; candidates selected on the first {d['n_train']} days, scored on the rest)\n")
    sel = d["selected"]; cands = d["candidates"]
    rows = []
    for m, lab in (("seasonal_nss", "seasonal NSS"), ("pspline", "P-spline"), ("kernel_ridge", "seasonal kernel ridge")):
        s = sel[m]; c = next(c for c in cands if c["method"] == m and c["label"] == s["label"])
        rows.append([lab, s["label"], f"{s['loo_test_mean_abs']:.4f}", f"{s['loo_test_mean_abs_pct']:.3f}%", f"{s['vs_nss_pct']:+.1f}% [{s['vs_nss_ci95'][0]:+.1f}, {s['vs_nss_ci95'][1]:+.1f}]", f"{s['extrapolation_test_mean_abs']:.4f}", f"{c['by_gap']['0']['loo_mean_abs']:.4f}", f"{c['by_gap']['>12']['loo_mean_abs']:.4f}"] + [f"{c['by_year'].get(y, float('nan')):.4f}" for y in sorted(c["by_year"])])
    table(["model", "selected", "test LOO mean abs err", "test LOO %", "vs NSS (paired bootstrap 95% CI)", "test extrapolation err", "LOO on complete days", "LOO on days >12 missing"] + [f"LOO {y}" for y in sorted(cands[0]["by_year"])], rows)
    ht = d["hedge_test"]
    P(f"Hedge test on the {ht['n_days']} complete days: the month-{ht['target_month']} contract is dropped, priced off the curve built from the rest and hedged with that curve's key-rate sensitivities; next-day hedged P&L std in {UNIT[root]} (unhedged {ht['unhedged_std']:.3f}):\n")
    table(["hedge", "days", "hedged std", "reduction vs unhedged"], [[n.replace("_", " "), v["n"], f"{v['hedged_std']:.4f}", f"{100 * v['reduction_vs_unhedged']:.1f}%"] for n, v in ht["methods"].items()])
    P("All candidates (test-period LOO):\n")
    table(["method", "candidate", "LOO train", "LOO test", "median", "extrapolation"], [[c["method"], c["label"], f"{c['loo_train']:.4f}", f"{c['loo_test']:.4f}", f"{c['loo_median_abs']:.4f}", f"{c['extrapolation_mean_abs']:.4f}"] for c in cands])

# ---- EIA panel hedge test ---------------------------------------------------------------------------------------------
