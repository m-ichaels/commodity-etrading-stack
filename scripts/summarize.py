    P(f"## {NAMES[root]}: price impact from hourly bars ({d['bars']})\n")
    P("Pooled self-impact sign(Q) R/sigma = Y |Q|^delta on windows of h hourly bars, Q = tick-rule signed volume / daily volume; delta from a log-log fit on 16 volume bins, 95% CI by block bootstrap over days. Cross-impact: ridge of each contract's return on sign(Q_i)|Q_i|^delta of all contracts; R² on the raw windows. Decay: cumulative front-contract response after the window relative to the concurrent response.\n")
    table(["window", "windows", "days", "contracts", "delta [95% CI]", "Y", "R² concave (bins / raw)", "R² linear (bins / raw)", "R² self only", "R² self + cross", "cumulative response after 1, 3, 6, 12 windows"],
          [[f"{w['window_bars']}h", w["n_windows"], w["n_days"], w["n_contracts"], f"{w['delta']:.3f} [{w['delta_ci95'][0]:.3f}, {w['delta_ci95'][1]:.3f}]", f"{w['Y']:.3f}", f"{w.get('r2_concave_bins', float('nan')):.3f} / {w['r2_concave']:.3f}", f"{w.get('r2_linear_bins', float('nan')):.3f} / {w['r2_linear']:.3f}", f"{w['r2_self_only']:.3f}", f"{w['r2_self_plus_cross']:.3f}", " / ".join(f"{w['decay'][k]:.2f}" for k in (0, 2, 5, 11) if k < len(w["decay"]))] for w in d["windows"]])
